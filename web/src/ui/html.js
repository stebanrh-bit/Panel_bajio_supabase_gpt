/** Escapa texto antes de insertarlo en HTML, también cuando forma parte de un atributo. */
export function escapeHtml(value) {
  const replacements = {
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    '"': "&quot;",
    "'": "&#39;",
  };

  return String(value ?? "").replace(
    /[&<>"']/g,
    (character) => replacements[character],
  );
}
